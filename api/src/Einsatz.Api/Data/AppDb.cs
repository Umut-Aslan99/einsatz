using Einsatz.Domain;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace Einsatz.Api.Data;

public sealed class AppDb(DbContextOptions<AppDb> options) : DbContext(options)
{
    public DbSet<User> Users => Set<User>();
    public DbSet<Customer> Customers => Set<Customer>();
    public DbSet<Machine> Machines => Set<Machine>();
    public DbSet<Article> Articles => Set<Article>();
    public DbSet<Job> Jobs => Set<Job>();
    public DbSet<IntegrationRecord> Integrations => Set<IntegrationRecord>();
    public DbSet<ProcessedCommand> ProcessedCommands => Set<ProcessedCommand>();

    /// <summary>
    /// PostgreSQL stores instants in UTC. Devices and the server's local clock (Europe/Berlin) produce
    /// offsets like +02:00, so every timestamp is normalised here, once, instead of at each call site.
    /// </summary>
    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        configurationBuilder.Properties<DateTimeOffset>().HaveConversion<UtcConverter>();
        configurationBuilder.Properties<DateTimeOffset?>().HaveConversion<UtcConverter>();
    }

    private sealed class UtcConverter() : ValueConverter<DateTimeOffset, DateTimeOffset>(v => v.ToUniversalTime(), v => v);

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        var b = modelBuilder;
        b.Entity<User>(e =>
        {
            e.HasIndex(u => u.Login).IsUnique();
            e.Property(u => u.Login).HasMaxLength(64);
            e.Property(u => u.Name).HasMaxLength(128);
            e.Property(u => u.Role).HasConversion<string>().HasMaxLength(16);
        });
        b.Entity<Customer>(e => e.HasIndex(c => c.Number).IsUnique());
        b.Entity<Machine>(e => e.HasOne<Customer>().WithMany().HasForeignKey(m => m.CustomerId));
        b.Entity<Article>(e =>
        {
            e.HasKey(a => a.Number);
            e.Property(a => a.Price).HasPrecision(12, 2);
        });

        b.Entity<Job>(e =>
        {
            e.HasIndex(j => j.Number).IsUnique();
            e.HasIndex(j => new { j.TechnicianId, j.ScheduledFor });
            e.Property(j => j.Status).HasConversion<string>().HasMaxLength(16);
            e.Property(j => j.Version).IsRowVersion();
            e.HasOne(j => j.Customer).WithMany().HasForeignKey(j => j.CustomerId);
            e.HasOne(j => j.Machine).WithMany().HasForeignKey(j => j.MachineId);
            e.HasOne(j => j.Technician).WithMany().HasForeignKey(j => j.TechnicianId);
            e.OwnsOne(j => j.Signature);
            e.HasMany(j => j.TimeEntries).WithOne().HasForeignKey("JobId").OnDelete(DeleteBehavior.Cascade);
            e.HasMany(j => j.Materials).WithOne().HasForeignKey("JobId").OnDelete(DeleteBehavior.Cascade);
            e.HasMany(j => j.Photos).WithOne().HasForeignKey("JobId").OnDelete(DeleteBehavior.Cascade);
            e.Ignore(j => j.TotalMinutes);
            e.Ignore(j => j.MaterialTotal);
            e.Ignore(j => j.IsEditable);
        });
        // Child keys are generated by the domain/device, never by the database. Without ValueGeneratedNever
        // EF would treat a new entry with a set key as existing and issue an UPDATE instead of an INSERT.
        b.Entity<TimeEntry>(e =>
        {
            e.Property(t => t.Id).ValueGeneratedNever();
            e.Ignore(t => t.Minutes);
        });
        b.Entity<MaterialLine>(e =>
        {
            e.Property(m => m.Id).ValueGeneratedNever();
            e.Property(m => m.Quantity).HasPrecision(10, 3);
            e.Property(m => m.UnitPrice).HasPrecision(12, 2);
            e.Ignore(m => m.Total);
        });
        b.Entity<Photo>().Property(p => p.Id).ValueGeneratedNever();

        b.Entity<IntegrationRecord>(e =>
        {
            e.HasIndex(i => i.JobId);
            e.HasOne<Job>().WithMany().HasForeignKey(i => i.JobId).OnDelete(DeleteBehavior.Cascade);
        });
        b.Entity<ProcessedCommand>(e =>
        {
            e.Property(p => p.Id).ValueGeneratedNever();
            e.HasOne<Job>().WithMany().HasForeignKey(p => p.JobId).OnDelete(DeleteBehavior.Cascade);
        });
    }
}

public static class DbQueries
{
    /// <summary>Everything needed to change a job (including photo bytes).</summary>
    public static IQueryable<Job> Full(this IQueryable<Job> jobs) => jobs
        .Include(j => j.Customer).Include(j => j.Machine).Include(j => j.Technician)
        .Include(j => j.TimeEntries).Include(j => j.Materials).Include(j => j.Photos)
        .AsSplitQuery();
}
